// PURPOSE: Build the one-bit land mask painted on the Earth globe (one bit per degree, 360 x 180)
//          from Natural Earth's 1:110m land polygons (public domain).
// USAGE:   node scripts/build-land.mjs [--offline]
//          Without --offline it fetches the GeoJSON into data-src/naturalearth/ first.
// OUTPUT:  src/data/land.ts; one ASCII summary line.
// VERSION HISTORY:
//   1.0  2026-11-27  Initial release.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const URL_LAND = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson';
const raw = join(root, 'data-src', 'naturalearth', 'ne_110m_land.geojson');

if (!process.argv.includes('--offline')) {
  const res = await fetch(URL_LAND, { headers: { 'user-agent': 'node-fetch' } });
  if (!res.ok) throw new Error(`fetch failed: ${res.status}`);
  await mkdir(join(root, 'data-src', 'naturalearth'), { recursive: true });
  await writeFile(raw, Buffer.from(await res.arrayBuffer()));
}

const geo = JSON.parse(await readFile(raw, 'utf8'));
const polygons = [];
for (const f of geo.features) {
  const g = f.geometry;
  if (g.type === 'Polygon') polygons.push(g.coordinates);
  else if (g.type === 'MultiPolygon') polygons.push(...g.coordinates);
}

// Even-odd point-in-polygon over all rings of a polygon (holes included).
function inside(lon, lat, rings) {
  let hit = false;
  for (const ring of rings) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i];
      const [xj, yj] = ring[j];
      if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
    }
  }
  return hit;
}

const boxes = polygons.map((rings) => {
  let x0 = Infinity, x1 = -Infinity, y0 = Infinity, y1 = -Infinity;
  for (const [x, y] of rings[0]) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
  return [x0, x1, y0, y1];
});

const W = 360, H = 180;
const bits = new Uint8Array((W * H) / 8);
let landCells = 0;
for (let y = 0; y < H; y++) {
  const lat = 90 - (y + 0.5);
  for (let x = 0; x < W; x++) {
    const lon = x + 0.5 - 180;
    let isLand = false;
    for (let p = 0; p < polygons.length && !isLand; p++) {
      const [x0, x1, y0, y1] = boxes[p];
      if (lon < x0 || lon > x1 || lat < y0 || lat > y1) continue;
      isLand = inside(lon, lat, polygons[p]);
    }
    if (isLand) { const i = y * W + x; bits[i >> 3] |= 1 << (7 - (i & 7)); landCells++; }
  }
}

const b64 = Buffer.from(bits).toString('base64');
const lines = b64.match(/.{1,120}/g).map((l) => `  '${l}',`).join('\n');
const out = `// Generated by scripts/build-land.mjs from Natural Earth 1:110m land (public domain,
// naturalearthdata.com). One bit per degree, 360 x 180, row 0 at the north pole, column 0 at
// longitude -180, most significant bit first. Do not edit by hand.
const B64 = [
${lines}
].join('');

function decode(text: string): Uint8Array {
  const bin = atob(text);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

export const LAND_MASK: Uint8Array = decode(B64);
`;
await writeFile(join(root, 'src', 'data', 'land.ts'), out);
console.log(`land: ${polygons.length} polygons, ${landCells} of ${W * H} cells are land (${((100 * landCells) / (W * H)).toFixed(1)} percent of the grid)`);
